/// How the WebAssembly runtime finds a string in another (`__nanyx_string_index_between`): a loop over the bytes that checks
/// each place by its first byte before it compares the rest. Written in Nanyx, each step of the search called a helper
/// to add, one to clamp an index and one to read a byte, which made it several times slower than this.
module internal Transpiler.Wasm.StringSearch

/// The helper `name`: `s needle from last -> index`, the byte index of the first occurrence of `needle` in `s` that
/// starts from `from` (taken as 0 when it is below 0) to `last` (taken as no further than where `needle` still fits), or
/// -1. An empty `needle` is found at `from` unless that is past `last`. It borrows both strings, as every helper does.
/// `stringLength` is the helper that gives a string's length.
let helper (name: string) (stringLength: string) =
    [ $"(func ${name} (param $s i32) (param $needle i32) (param $from i32) (param $last i32) (result i32)"
      "  (local $length i32)"
      "  (local $needleLength i32)"
      "  (local $fits i32)"
      "  (local $first i32)"
      "  (local $j i32)"
      "  local.get $s"
      $"  call ${stringLength}"
      "  local.set $length"
      "  local.get $needle"
      $"  call ${stringLength}"
      "  local.set $needleLength"
      "  local.get $from"
      "  i32.const 0"
      "  local.get $from"
      "  i32.const 0"
      "  i32.gt_s"
      "  select"
      "  local.set $from"
      // The last place `needle` fits, which is below `from` when it can't.
      "  local.get $length"
      "  local.get $needleLength"
      "  i32.sub"
      "  local.tee $fits"
      "  local.get $last"
      "  local.get $last"
      "  local.get $fits"
      "  i32.gt_s"
      "  select"
      "  local.set $last"
      "  local.get $needleLength"
      "  i32.eqz"
      "  if"
      "    local.get $from"
      "    i32.const -1"
      "    local.get $from"
      "    local.get $last"
      "    i32.le_s"
      "    select"
      "    return"
      "  end"
      "  local.get $needle"
      "  i32.load8_u"
      "  local.set $first"
      "  block $notFound"
      "    loop $place"
      "      local.get $from"
      "      local.get $last"
      "      i32.gt_s"
      "      br_if $notFound"
      "      local.get $s"
      "      local.get $from"
      "      i32.add"
      "      i32.load8_u"
      "      local.get $first"
      "      i32.eq"
      "      if"
      "        i32.const 1"
      "        local.set $j"
      "        block $differs"
      "          loop $compare"
      "            local.get $j"
      "            local.get $needleLength"
      "            i32.ge_s"
      "            if"
      "              local.get $from"
      "              return"
      "            end"
      "            local.get $s"
      "            local.get $from"
      "            i32.add"
      "            local.get $j"
      "            i32.add"
      "            i32.load8_u"
      "            local.get $needle"
      "            local.get $j"
      "            i32.add"
      "            i32.load8_u"
      "            i32.ne"
      "            br_if $differs"
      "            local.get $j"
      "            i32.const 1"
      "            i32.add"
      "            local.set $j"
      "            br $compare"
      "          end"
      "        end"
      "      end"
      "      local.get $from"
      "      i32.const 1"
      "      i32.add"
      "      local.set $from"
      "      br $place"
      "    end"
      "  end"
      "  i32.const -1"
      ")" ]
